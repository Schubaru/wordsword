// Builds Wordsword/Games/haikuzy-near.txt: for every hidden word in haikuzy.txt, the words that
// mean something like it, closest first, plus the two distances the app needs to score anything
// else with Apple's on-device word embedding. Run after adding haiku:
//
//   swiftc -O Scripts/make-haikuzy-near.swift -o /tmp/near && /tmp/near
//
// Each line:  answer near base: word word word …
//   near  — embedding distance from the answer to its 5th-nearest neighbour (scores ~95)
//   base  — the median distance from the answer to 400 everyday words (scores 1)
//   words — the haiku's own extras (`{word+a,b}`) first, then Datamuse "means like" (ml=), single words in haiku-words.txt only, minus forms of the
//           answer, and past Datamuse's first 25 minus anything the embedding doesn't put clearly
//           nearer than an everyday word — that drops stray senses (heron → "path", "daughter").
// Needs the network (Datamuse) and macOS (NaturalLanguage). Same inputs, same bytes out, as long
// as Datamuse answers the same.
import Foundation
import NaturalLanguage

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let games = root.appendingPathComponent("Wordsword/Games")
func lines(_ name: String) -> [String] {
    (try! String(contentsOf: games.appendingPathComponent(name), encoding: .utf8)).split(separator: "\n").map(String.init)
}

let words = Set(lines("haiku-words.txt"))
let common = lines("haiku-common.txt")
/// (answer, topic, extras): `{cardinal:bird+bird,robin}` is the word "cardinal", looked up in the
/// sense of a bird, with "bird" and "robin" counted as its closest words.
let answers = lines("haikuzy.txt").compactMap { l -> (String, String?, [String])? in
    guard !l.hasPrefix("#"), let o = l.firstIndex(of: "{"), let c = l.firstIndex(of: "}") else { return nil }
    let inside = l[l.index(after: o)..<c]
    let halves = inside.split(separator: "+", maxSplits: 1).map(String.init)
    let extras = halves.count > 1 ? halves[1].split(separator: ",").map(String.init) : []
    let parts = halves[0].split(separator: ":").map(String.init)
    return (parts[0], parts.count > 1 ? parts[1] : nil, extras)
}
let embedding = NLEmbedding.wordEmbedding(for: .english)!
// Every 40th of the first 16k everyday words: the same 400 for every answer.
let everyday = stride(from: 0, to: min(16_000, common.count), by: 40).map { common[$0] }.filter { embedding.contains($0) }

/// The app's rule for "a form of the answer" (HaikuzyScore.isAnswer), so the list never holds one.
func sameWord(_ w: String, _ a: String) -> Bool {
    if w == a { return true }
    func plural(_ x: String, _ y: String) -> Bool {
        x == y + "s" || x == y + "es" || (y.hasSuffix("y") && x == y.dropLast() + "ies")
    }
    if plural(w, a) || plural(a, w) { return true }
    return a.hasSuffix("ed") && (w == String(a.dropLast()) || w == String(a.dropLast(2)))
}

func datamuse(_ w: String, topic: String?) -> [String] {
    let url = URL(string: "https://api.datamuse.com/words?ml=\(w)&max=1000" + (topic.map { "&topics=\($0)" } ?? ""))!
    let data = try! Data(contentsOf: url)
    let rows = try! JSONSerialization.jsonObject(with: data) as! [[String: Any]]
    return rows.compactMap { $0["word"] as? String }
}

/// Fine to guess, never to reward with a high score just because a thesaurus links them.
let crude: Set<String> = ["penis", "gland", "glans", "testicle", "testis", "scrotum", "nut", "nuts", "balls", "heroin", "cocaine"]

var out = ["# Generated by Scripts/make-haikuzy-near.swift from haikuzy.txt — don't edit by hand."]
var seen = Set<String>()
for (a, topic, extras) in answers where seen.insert(a).inserted {
    guard embedding.contains(a) else { print("!! \(a) isn't in the word embedding"); continue }
    let near = embedding.neighbors(for: a, maximumCount: 5).last?.1 ?? 0.8
    let ds = everyday.map { embedding.distance(between: a, and: $0) }.sorted()
    let base = ds[ds.count / 2]
    var kept: [String] = extras
    var taken = Set(extras)
    for (i, w) in datamuse(a, topic: topic).enumerated() where w.allSatisfy({ $0.isASCII && $0.isLowercase }) && words.contains(w) && !sameWord(w, a) {
        // Datamuse's first 25 are its surest; past them, keep only what the embedding puts at least a
        // quarter of the way from an everyday word towards the answer — the rest is a sense of the
        // word the haiku isn't using. (Not the first 25: the embedding reads "rime" as "rhyme".)
        if i >= 25, embedding.contains(w), embedding.distance(between: a, and: w) > base - 0.25 * (base - near) { continue }
        if crude.contains(w) { continue }
        if taken.insert(w).inserted { kept.append(w) }
        if kept.count == 300 { break }
    }
    out.append("\(a) \(String(format: "%.4f", near)) \(String(format: "%.4f", base)): " + kept.joined(separator: " "))
    print(a, kept.count, kept.prefix(12).joined(separator: " "))
}
try! (out.joined(separator: "\n") + "\n").write(to: games.appendingPathComponent("haikuzy-near.txt"), atomically: true, encoding: .utf8)
